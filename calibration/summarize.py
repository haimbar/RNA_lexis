"""Build calibration/results/SUMMARY.md from the CSV files written by the two run_*.py scripts."""
import csv
from pathlib import Path

R = Path(__file__).resolve().parent / "results"


def rd(name):
    return list(csv.DictReader(open(R / name, encoding="utf-8")))


def table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out) + "\n"


def f(x, nd=3):
    return f"{float(x):.{nd}f}"


def main():
    L = ["# Calibration results (generated by summarize.py)\n"]

    # ---- codon: quality vs truth -------------------------------------------------
    q = rd("background_quality.csv")
    bgs = ["hybrid_s16", "hybrid_s64", "hybrid_s256", "hybrid_s1024", "ntpos", "order0_flat_pc0.1", "order0_flat_pc1",
           "order0_flat_pc2", "order1_flat_pc1", "order1_backoff_s64", "reference_usage"]
    cols = [(k, N) for k in "AB" for N in (100, 300, 1500)]

    def Q(k, N, bg, col):
        return [x for x in q if x["null"] == k and int(x["N"]) == N and x["background"] == bg and x["word_length"] == "3"][0][col]
    L.append("## Codons: error of each background against the true model (words of 3 codons)\n")
    L.append("Cells: KL per word (nats), lower is better. Columns: null A (iid codons) or B (amino-acid Markov), N codons.\n")
    L.append(table(["background"] + [f"{k}{N}" for k, N in cols],
                   [[bg] + [f(Q(k, N, bg, "kl_per_word")) for k, N in cols] for bg in bgs]))

    # ---- codon: bias on repeated words ---------------------------------------------
    rb = rd("repeated_word_bias.csv")
    bgs2 = ["order0_flat_pc1", "hybrid_s64", "hybrid_s256", "masked_order0_flat_pc1", "masked_hybrid_s256", "order1_backoff_s64", "reference_usage"]

    def B(k, N, bg, col):
        return [x for x in rb if x["null"] == k and int(x["N"]) == N and x["background"] == bg][0][col]
    L.append("## Codons: bias of the expected count on words seen at least twice\n")
    L.append("Cells: mean log(expected / true expected); negative = the background expects too little, so chance repeats look significant.\n")
    L.append(table(["background"] + [f"{k}{N}" for k, N in cols],
                   [[bg] + [f(B(k, N, bg, "mean_log_expected_ratio"), 2) for k, N in cols] for bg in bgs2]))
    L.append("Fraction of those words whose expected count is at least 2x too small:\n")
    L.append(table(["background"] + [f"{k}{N}" for k, N in cols],
                   [[bg] + [f(B(k, N, bg, "frac_underestimated_2x"), 2) for k, N in cols] for bg in bgs2]))

    # ---- codon: multiple-testing family -------------------------------------------
    nul = rd("scoring_null.csv")

    def FP(k, N, bg, fam):
        return [x for x in nul if x["null"] == k and int(x["N"]) == N and x["background"] == bg and x["family"] == fam][0]["fp_rate"]
    L.append("## Codons: false positives per null text, by multiple-testing family\n")
    L.append("Strict rule (q <= 0.05, enrichment >= 10). `candidates` = BH over the repeated words only, as score_exact_motifs does; "
             "`observed` = over every word seen; `possible` = over all 64^k words of the lengths 2 to 6 taken together; "
             "`bylength` = within each length k over that length's 64^k words (the family implemented for new alphabets).\n")
    rows = []
    for fam in ("candidates", "observed", "possible", "bylength"):
        for bg in ("order0_flat_pc1", "hybrid_s64", "order1_flat_pc1", "oracle"):
            rows.append([fam, bg] + [f(FP(k, N, bg, fam), 2) for k, N in cols])
    L.append(table(["family", "background"] + [f"{k}{N}" for k, N in cols], rows))

    # ---- codon: power ----------------------------------------------------------------
    pw = rd("scoring_power.csv")

    def P(N, Lp, r, bg, fam="possible"):
        return [x for x in pw if int(x["N"]) == N and int(x["phrase_codons"]) == Lp and int(x["copies"]) == r
                and x["background"] == bg and x["family"] == fam][0]["recall"]
    L.append("## Codons: recall of a planted phrase\n")
    L.append("Families `possible` (lengths taken together) and `bylength` (within each length), flat order 0 background.\n")
    cells0 = [(3, 4), (4, 3), (4, 4), (6, 2), (6, 3)]
    L.append(table(["N", "family"] + [f"{a}/{b}" for a, b in cells0],
                   [[N, fam] + [f(P(N, Lp, r, "order0_flat_pc1", fam), 2) for Lp, r in cells0]
                    for N in (100, 300, 1500) for fam in ("possible", "bylength")]))
    L.append("All backgrounds, family = possible:\n")
    L.append("Phrase length in codons / number of copies.\n")
    cells = [(3, 4), (4, 3), (4, 4), (6, 2), (6, 3)]
    rows = []
    for N in (100, 300, 1500):
        for bg in ("order0_flat_pc1", "hybrid_s256", "masked_order0_flat_pc1", "order1_flat_pc1", "oracle"):
            rows.append([N, bg] + [f(P(N, Lp, r, bg), 2) for Lp, r in cells])
    L.append(table(["N", "background"] + [f"{a}/{b}" for a, b in cells], rows))

    # ---- discovery + nucleotide reference -------------------------------------------
    L.append("## `rna_lexis_stat_cli rank-cores` on iid nucleotide text (nucleotide_cli_check.py)\n")
    L.append("Share of random texts (nothing planted) in which at least one core is called statistically supported.\n")
    L.append(table(["nt", "settings", "--min-xmotif-len", "--min-count", "--candidate-min-len", "texts", "fraction with candidates", "fraction with a supported core"],
                   [[r["n_nt"], r["settings"], r["min_xmotif_len"], r["min_count"], r["candidate_min_len"], r["texts"],
                     r["frac_with_candidates"], r["frac_with_supported_core"]] for r in rd("nucleotide_cli_check.csv")]))
    pl = rd("pipeline_null.csv")
    mx = max(float(v.split("=")[1]) for r in pl for v in r["fp_rate_by_background"].split(";"))
    wc = max(float(r["frac_with_candidates"]) for r in pl)
    L.append(f"On codon null text the full pipeline (xmotifs, shared substrings, scoring) found candidates in at most {wc:.3f} of texts, "
             f"over minlen 2-4 and N = 100-1500, and the highest false-positive rate over all backgrounds was {mx:.3f}.\n")

    # ---- letters ---------------------------------------------------------------------
    ln = rd("letters_null.csv")
    corp = ("antony", "homer", "genesis", "constitution")

    def G(c, m, N, o, col):
        return float([x for x in ln if x["corpus"] == c and int(x["true_order"]) == m and int(x["N"]) == N
                      and int(x["background_order"]) == o][0][col])
    Ns = sorted({int(x["N"]) for x in ln})
    for col, title in (("fp_strict", "Letters: strict false-positive rate per null text (mean over 4 corpora; worst corpus in brackets)"),):
        L.append(f"## {title}\n")
        L.append("True order = order of the Markov chain the null text is drawn from. Background order = order of the background (flat pseudocount 1). "
                 "Family = all possible words (K^k).\n")
        rows = []
        for m in (0, 1, 2):
            for N in Ns:
                rows.append([m, N] + [f"{sum(G(c, m, N, o, col) for c in corp) / 4:.2f} ({max(G(c, m, N, o, col) for c in corp):.2f})" for o in (0, 1, 2, 3)])
        L.append(table(["true order", "N letters", "order 0", "order 1", "order 2", "order 3"], rows))
    L.append("## Letters: strict false-positive rate at order 1, correction within each word length\n")
    rows = []
    for m in (0, 1, 2):
        for N in Ns:
            rows.append([m, N, f"{sum(G(c, m, N, 1, 'fp_strict_bylength') for c in corp) / 4:.3f}",
                         f"{max(G(c, m, N, 1, 'fp_strict_bylength') for c in corp):.3f}"])
    L.append(table(["true order", "N letters", "mean over corpora", "worst corpus"], rows))
    L.append("## Letters: KL per 3-letter word (mean over corpora)\n")
    L.append("Order 3 equals order 0 on 3-letter words by construction (as in MarkovBackground, the first `order` symbols of a word use the marginal).\n")
    rows = []
    for m in (0, 1, 2):
        for N in Ns:
            rows.append([m, N] + [f"{sum(G(c, m, N, o, 'kl_per_word') for c in corp) / 4:.3f}" for o in (0, 1, 2)])
    L.append(table(["true order", "N letters", "order 0", "order 1", "order 2"], rows))

    lp = rd("letters_power.csv")

    def LP(c, m, N, Lp, cp, o):
        return float([x for x in lp if x["corpus"] == c and int(x["true_order"]) == m and int(x["N"]) == N and int(x["phrase_letters"]) == Lp
                      and int(x["copies"]) == cp and int(x["background_order"]) == o][0]["recall"])
    L.append("## Letters: recall of a planted phrase at the calibrated order (order 1), mean over corpora\n")
    cells = [(3, 6), (3, 12), (4, 4), (4, 8), (6, 2), (6, 3)]
    rows = []
    for m in (0, 1):
        for N in Ns:
            rows.append([m, N] + [f"{sum(LP(c, m, N, a, b, 1) for c in corp) / 4:.2f}" for a, b in cells])
    L.append(table(["true order", "N letters"] + [f"{a}/{b}" for a, b in cells], rows))

    lr = rd("letters_real.csv")
    L.append("## Real texts: words called significant (strict) by background order\n")
    L.append(table(["corpus", "order 0", "order 1", "order 2", "order 3"],
                   [[c] + [[x for x in lr if x["corpus"] == c and int(x["background_order"]) == o][0]["supported_words_strict"] for o in range(4)]
                    for c in corp]))
    # ---- discovery settings per alphabet ---------------------------------------------------
    if (R / "pipeline_defaults.csv").exists():
        pd_rows = rd("pipeline_defaults.csv")
        L.append("## Discovery settings per alphabet (run_pipeline_defaults.py)\n")
        L.append("The whole CLI pipeline (xmotifs, shared substrings, scoring) on null texts and on planted core "
                 "families. `FP` = share of null texts with at least one statistically supported core (worst over "
                 "all null models and lengths); `recall` = share of planted cores recovered (mean over core "
                 "lengths, copies, text lengths and null models). Settings are (shortest xmotif, shortest core "
                 "candidate, fewest occurrences).\n")
        rows = []
        for alph, label in (("codon", "codon"), ("amino", "amino acid"), ("letters", "Latin letters")):
            settings = sorted({(int(r["xmotif_minlen"]), int(r["cand_minlen"]), int(r["min_count"]))
                               for r in pd_rows if r["alphabet"] == alph})
            for st in settings:
                sel = [r for r in pd_rows if r["alphabet"] == alph and
                       (int(r["xmotif_minlen"]), int(r["cand_minlen"]), int(r["min_count"])) == st]
                fp = max(float(r["rate"]) for r in sel if r["core_units"] == "")
                rec = [float(r["rate"]) for r in sel if r["core_units"] != ""]
                rows.append([label, f"{st[0]}, {st[1]}, {st[2]}", f"{fp:.3f}", f"{sum(rec) / len(rec):.3f}"])
        L.append(table(["alphabet", "setting", "FP (worst)", "recall (mean)"], rows))
    if (R / "order_rule_checks.csv").exists():
        L.append("## Order rule, beyond the first calibration (run_order_rule_checks.py)\n")
        L.append("Codon text from 4,000 to 20,000 codons (the rule switches to order 1 at 4,096) and amino acids "
                 "(K = 21, switch at 441 residues). Bias = mean log(expected / true expected) on the words seen at "
                 "least twice (negative = anti-conservative); FP = share of null texts with a supported word.\n")
        L.append(table(["null", "N", "order", "bias", "frac under-estimated 2x", "FP"],
                       [[r["null"], r["N"], r["background_order"], r["mean_log_expected_ratio"],
                         r["frac_underestimated_2x"], r["fp_rate"]] for r in rd("order_rule_checks.csv")]))
    (R / "SUMMARY.md").write_text("\n".join(L), encoding="utf-8")
    print("wrote", R / "SUMMARY.md")


if __name__ == "__main__":
    main()
